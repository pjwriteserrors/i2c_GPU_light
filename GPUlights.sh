#!/usr/bin/env bash

set -euo pipefail

# usage
usage() {
	cat <<EOF
Usage: $0 -m <mode> -c <hexcolor> -b <brightness> | -l

  -m MODE		(e.g. static, rainbow) (see -l) (will default to static)
  -c COLOR		(e.g. FF00FF for pink)		(will default to FF0000)
  -b BRIGHTNESS		(e.g. 3 for brightest) (0-3)	(will default to 3)
  -l LIST MODES		Lists all available modes
  -h HELP		Prints this help
EOF
}

# list
list() {
	cat <<EOF
static (color)
rainbow
aurora
meteor
marquee
twinkling
color_cycle
color_breathing
breathe (color)
central_meteor
blinking (color)
aqua
flare
forest
stary
firework
lava
tetris
blackhole
sakura (color)
emergency
laser (color)
two_blink (color)
off
EOF
}

# set default settings
mode="static"
hex="FF0000"
brightness="3"

# get getops args
while getopts "m:c:b:lh" opt; do
	case "$opt" in
		m) mode=$OPTARG ;;
		c) hex=$OPTARG ;;
		b) brightness=$OPTARG ;;
		l) list; exit 0 ;;
		h) usage; exit 0 ;;
		\?) exit 1 ;;
	esac
done

# check if brightness is right
if ! [[ $brightness =~ ^[0-3]$ ]]; then
	echo "Brightness needs to be a number from 0-3" >&2
	exit 2
fi

# check if hex format is right
if [[ ! $hex =~ ^[0-9A-F]{6}$ ]]; then
	echo "Color should be in HEX format (without '#')"
	exit 3
fi

echo "Mode		= $mode"
echo "Color		= $hex"
echo "Brightness	= $brightness"

# check brightness
if [[ -z $brightness || $brightness == "3" ]]; then
	bri=0x40
elif [[ $brightness == "2" ]]; then
	bri=0x02
elif [[ $brightness == "1" ]]; then
	bri=0x01
elif [[ $brightness == "0" ]]; then
	bri=0x00
fi

# Extract colors from hex format
red="0x${hex:0:2}"
green="0x${hex:2:2}"
blue="0x${hex:4:2}"

# set the modes
case $mode in
	"static")
		i2cset -y 1 0x50 0x02 $red $green $blue i
		i2cset -y 1 0x50 0x30 0x01 i
		i2cset -y 1 0x50 0x2B 0x00 i
		i2cset -y 1 0x50 0x2D $bri i
		i2cset -y 1 0x50 0x40 0x5A i
		;;

	"rainbow")
		i2cset -y 1 0x50 0x02 0xFF 0x00 0x00 i
                i2cset -y 1 0x50 0x21 0x00 0x30 i
		i2cset -y 1 0x50 0x30 0x11 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
                ;;
	"aurora")
		i2cset -y 1 0x50 0x02 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x21 0x01 0x10 0x06 i
                i2cset -y 1 0x50 0x30 0x12 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"meteor")
		i2cset -y 1 0x50 0x02 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x21 0x04 0x00 i
                i2cset -y 1 0x50 0x30 0x13 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"marquee")
		i2cset -y 1 0x50 0x02 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x21 0x01 0x01 i
                i2cset -y 1 0x50 0x30 0x14 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"twinkling")
		i2cset -y 1 0x50 0x02 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x21 0x03 0x02 i
                i2cset -y 1 0x50 0x30 0x15 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"color_cycle")
		i2cset -y 1 0x50 0x02 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x21 0x09 0x01 0x09 i
                i2cset -y 1 0x50 0x30 0x16 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"color_breathing")
		i2cset -y 1 0x50 0x02 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x21 0x01 0x01 i
                i2cset -y 1 0x50 0x30 0x17 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"breathe")
		i2cset -y 1 0x50 0x02 $red $green $blue i
                i2cset -y 1 0x50 0x21 0x06 0x00 i
                i2cset -y 1 0x50 0x30 0x02 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"off")
		i2cset -y 1 0x50 0x02 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x30 0x19 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"central_meteor")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
                i2cset -y 1 0x50 0x21 0x00 0x00 i
                i2cset -y 1 0x50 0x30 0x18 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"blinking")
		i2cset -y 1 0x50 0x02 $red $green $blue i
                i2cset -y 1 0x50 0x21 0x00 0x01 i
                i2cset -y 1 0x50 0x30 0x03 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"aqua")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
		i2cset -y 1 0x50 0x1A 0x00 0x90 0xFF 0x00 0x00 0xFF i
                i2cset -y 1 0x50 0x21 0x01 0x01 i
                i2cset -y 1 0x50 0x30 0x20 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"flare")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
		i2cset -y 1 0x50 0x1A 0xFF 0x00 0x00 0xFF 0x50 0x00 i
                i2cset -y 1 0x50 0x21 0x01 i
                i2cset -y 1 0x50 0x30 0x21 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"forest")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
		i2cset -y 1 0x50 0x1A 0x00 0xFF 0x00 0x45 0xEE 0x90 i
                i2cset -y 1 0x50 0x21 0x01 i
                i2cset -y 1 0x50 0x30 0x22 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"stary")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
                i2cset -y 1 0x50 0x21 0x03 i
                i2cset -y 1 0x50 0x30 0x23 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"firework")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
                i2cset -y 1 0x50 0x21 0x09 i
                i2cset -y 1 0x50 0x30 0x23 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"lava")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
                i2cset -y 1 0x50 0x21 0x05 i
                i2cset -y 1 0x50 0x30 0x24 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"tetris")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
                i2cset -y 1 0x50 0x21 0x06 i
                i2cset -y 1 0x50 0x30 0x25 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"blackhole")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
                i2cset -y 1 0x50 0x21 0x01 i
                i2cset -y 1 0x50 0x30 0x26 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"sakura")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
		i2cset -y 1 0x50 0x02 $red $green $blue i
                i2cset -y 1 0x50 0x21 0x00 0x00 i
                i2cset -y 1 0x50 0x30 0x27 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"emergency")
		i2cset -y 1 0x50 0x02 0xFF 0xFF 0xFF i
                i2cset -y 1 0x50 0x21 0x04 0x04 i
                i2cset -y 1 0x50 0x30 0x28 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"laser")
		i2cset -y 1 0x50 0x02 $red $green $blue i
                i2cset -y 1 0x50 0x21 0x08 0x08 i
                i2cset -y 1 0x50 0x30 0x29 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
	"two_blink")
		i2cset -y 1 0x50 0x02 $red $green $blue i
                i2cset -y 1 0x50 0x21 0x02 0x02 0x04 0x05 i
                i2cset -y 1 0x50 0x30 0x04 i
                i2cset -y 1 0x50 0x2B 0x00 i
                i2cset -y 1 0x50 0x2D $bri i
                i2cset -y 1 0x50 0x40 0x5A i
		;;
esac
